// 🧠 Interview Questions — Loops

// What is a loop?
// A loop repeatedly executes a block of code while a condition is true or
// until a specified number of iterations has been completed.

// Difference between for, while, and do...while.
// for: Best when initialization, condition, and update are known together.
// while: Checks the condition first and is useful when iterations are unknown.
// do...while: Runs the code at least once, then checks the condition.

// When should you use a for loop?
// Use it when you know how many times the loop should run or need an index.

// When should you use a while loop?
// Use it when the loop depends on a condition and the number of iterations is
// not known in advance.

// What is a nested loop?
// A loop inside another loop. The inner loop runs completely for each outer
// loop iteration.

// What is an infinite loop?
// A loop whose condition never becomes false, causing it to run continuously.

// Difference between break and continue.
// break exits the loop immediately; continue skips the current iteration and
// proceeds to the next one.

// Can a for loop run forever?
// Yes. For example: for (;;) { /* code */ }

// How do you stop a loop?
// Make its condition false, update its control variable correctly, or use
// break when an exit condition is met.

// What are common mistakes while using loops?
// Forgetting to update the control variable, using the wrong condition,
// creating an infinite loop, off-by-one errors, and unnecessarily nesting
// expensive loops.
