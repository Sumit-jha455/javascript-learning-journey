// 🧠 Interview Questions — Answers

// 1. What is a conditional statement?
// A conditional statement runs different code depending on whether a condition
// evaluates to true or false.

// 2. Difference between if and switch.
// `if` checks conditions or ranges using expressions. `switch` compares one
// value against several exact `case` values.

// 3. When should you use switch instead of if...else?
// Use `switch` when comparing one expression with many fixed, exact values.
// Use `if...else` for ranges, complex conditions, or different expressions.

// 4. What is nested if?
// A nested `if` is an `if` statement placed inside another `if` statement.

// 5. What is the ternary operator?
// It is a short form of `if...else`: condition ? valueIfTrue : valueIfFalse.

// 6. Difference between == and === in conditions.
// `==` compares values after type conversion, while `===` compares both value
// and type without conversion. `===` is generally preferred.

// 7. What happens if no switch case matches?
// No case code runs. If a `default` case exists, its code runs instead.

// 8. Why is break important in switch?
// `break` stops execution from continuing into the following cases. Without
// it, JavaScript usually performs fall-through.

// 9. Can if statements be nested?
// Yes. An `if` statement can be placed inside another `if`, `else`, or loop.

// 10. Difference between multiple if statements and if...else if.
// Multiple `if` statements are checked independently, so several blocks may
// run. In an `if...else if` chain, only the first matching block runs.
